/**
 * Round 1600: writes src/data/clubManagerCurve1View.ts, the curve 1 view the two dailies deal from before the age
 * read reaches them (onCurve1View in src/data/clubManagerWorldRosters.ts, CM_DAILY_NEW_NUMBERS_FROM in
 * src/lib/managerHotSeat.ts).
 *
 * The view holds, for every club of the main squads file AS IT STOOD at one commit (the last one before the flip,
 * when every rating was the value rating and every age the table's), a digest of its men's names in file order and
 * their ages, two digits a man. The ratings need no copy: the flip keeps each man's value rating in the file's `r`
 * and adds the age at load, so the view is the same file read with no age at the old ages.
 *
 *   node scripts/genCmCurve1View.mjs --from <sha>     write the view from that commit's squads file
 *   node scripts/genCmCurve1View.mjs --check          rebuild from the commit the view names and compare, byte for
 *                                                     byte (exit 1 on any difference; needs that commit: the remote
 *                                                     check kit fetches the whole history)
 *
 * The names digest is namesDigest's in src/data/clubManagerWorldRosters.ts (FNV-1a over the names joined by '|').
 * A club whose men changed after the view was cut keeps its own rows in the view (the engine checks the digest),
 * so a later re-bake of one club re-deals that club's days, which is the data changing, as Round 1044 has it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/data/clubManagerCurve1View.ts');
const SQUADS = 'src/data/clubManagerRosters.ts';
const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const fromAt = args.indexOf('--from');

function namesDigest(names) {
  let h = 2166136261 >>> 0;
  const s = names.join('|');
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; }
  return h.toString(16).padStart(8, '0');
}
const CLUB_LINE = /^  '(.*)': \[$/;
const ROW_LINE = /^    \{ n: '(.*)', p: '\w+', a: (\d+), v: [\d.]+, r: \d+ \},$/;
const unescape = s => s.replace(/\\'/g, "'").replace(/\\\\/g, '\\');
const esc = s => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

function viewOf(text) {
  const clubs = new Map();
  let club = null;
  for (const line of text.replaceAll('\r\n', '\n').split('\n')) {
    const c = CLUB_LINE.exec(line);
    if (c) { club = unescape(c[1]); clubs.set(club, { names: [], ages: [] }); continue; }
    const m = ROW_LINE.exec(line);
    if (!m || club === null) continue;
    const age = Number(m[2]);
    if (age < 10 || age > 99) throw new Error(`genCmCurve1View: ${unescape(m[1])} of ${club} is ${age}, which two digits cannot hold`);
    clubs.get(club).names.push(unescape(m[1]));
    clubs.get(club).ages.push(age);
  }
  return clubs;
}

function render(from, clubs) {
  let men = 0;
  const lines = [...clubs].filter(([, v]) => v.names.length).map(([club, v]) => {
    men += v.names.length;
    return `  '${esc(club)}': ['${namesDigest(v.names)}', '${v.ages.map(a => String(a).padStart(2, '0')).join('')}'],`;
  });
  return `// GENERATED by scripts/genCmCurve1View.mjs from ${SQUADS} at ${from}. DO NOT EDIT BY HAND.
// Round 1600: the curve 1 view of Club Manager's main squads file, ${men} men of ${lines.length} clubs: what Manager
// Hot Seat and Deadline Day deal from on a day before CM_DAILY_NEW_NUMBERS_FROM (src/lib/managerHotSeat.ts), so no
// day already played is dealt again on the age read. Each club: a digest of its men's names in file order, and
// their ages then, two digits a man. Check with: node scripts/genCmCurve1View.mjs --check
import type { Curve1View } from '@/data/clubManagerWorldRosters';

export const CM_CURVE1_VIEW: Curve1View = {
  from: '${from}',
  clubs: {
${lines.join('\n')}
  },
};
`;
}

const git = a => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
if (CHECK) {
  const committed = fs.readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n');
  const from = /from: '([0-9a-f]{7,40})'/.exec(committed)?.[1];
  if (!from) { console.log('genCmCurve1View: the view names no commit'); process.exit(1); }
  const again = render(from, viewOf(git(['show', `${from}:${SQUADS}`])));
  if (again !== committed) { console.log(`genCmCurve1View: the committed view is NOT what ${from}'s squads file gives`); process.exit(1); }
  console.log(`genCmCurve1View: the committed view is ${from}'s squads file, byte for byte`);
  process.exit(0);
}
if (fromAt < 0 || !args[fromAt + 1]) { console.log('genCmCurve1View: --from <sha> or --check'); process.exit(2); }
const from = git(['rev-parse', args[fromAt + 1]]).trim();
fs.writeFileSync(OUT, render(from, viewOf(git(['show', `${from}:${SQUADS}`]))));
console.log(`genCmCurve1View: wrote ${path.relative(ROOT, OUT)} from ${from}`);
