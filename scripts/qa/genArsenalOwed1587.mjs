// Round 1587: the hand over to the other lane (critic 1584 correction 9), GENERATED, never copied from a draft: every
// committed file outside this round's own data that names a sarandi man of arsenalLedger.json, by his stored spelling
// (and its accent free form when that differs), whole word, with the line and the text around the name. Those files were
// baked from the shared table before the apply (Club Manager's eras and roster, Soccer Career's club squads, fixtures),
// so they keep the men at Arsenal until their owners re-bake. Nothing here edits them, and a hit is a lead, not a
// verdict: a common name can be another man (the reader checks the line is the man at Arsenal).
// It greps the tracked files of the working tree (git grep, about two seconds; the same grep over HEAD's blobs takes
// minutes here) and refuses unless every tracked file equals HEAD, so what it writes is what HEAD holds.
// Run: node scripts/qa/genArsenalOwed1587.mjs [--check]   writes scripts/data/clubNamesakes1584/owedToChat1587.json
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DATA = path.join(ROOT, 'scripts', 'data', 'clubNamesakes1584');
const OUT = path.join(DATA, 'owedToChat1587.json');
const OUT_REL = 'scripts/data/clubNamesakes1584/owedToChat1587.json';
// This round's own data, generators, harness and migration, and prose (docs and markdown) are not baked files.
const SKIP = [/^scripts\/data\/clubNamesakes1584\//, /1587/, /^scripts\/simClubNamesakes\.mjs$/, /^docs\//, /\.md$/];
const git = (args) => {
  try { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 << 20 }); }
  catch (e) { if (e.status === 1) return ''; throw e; }
};
const dirty = git(['status', '--porcelain', '--untracked-files=no']).split('\n').filter((l) => l.trim() && !l.endsWith(OUT_REL));
if (dirty.length) { console.log('REFUSED: tracked files differ from HEAD, commit first:\n' + dirty.slice(0, 10).join('\n')); process.exit(2); }

const strip = (s) => s.normalize('NFD').replace(/\p{M}/gu, '');
const ledger = JSON.parse(fs.readFileSync(path.join(DATA, 'arsenalLedger.json'), 'utf8'));
const market = JSON.parse(fs.readFileSync(path.join(DATA, ledger.export), 'utf8'));
const nameOf = new Map(market.map((r) => [r.id, r.player_name]));
const men = ledger.men.filter((m) => m.verdict === 'sarandi').map((m) => nameOf.get(m.rows[0]));
const owner = new Map();
for (const name of men) for (const form of new Set([name, strip(name)])) (owner.get(form) ?? owner.set(form, []).get(form)).push(name);
const pats = [...owner.keys()].flatMap((f) => ['-e', f]);

const files = git(['grep', '-l', '-I', '-F', '-w', ...pats, '--', '.']).split('\n').filter(Boolean).filter((f) => !SKIP.some((re) => re.test(f))).sort();
const hits = [];
for (const file of files) {
  const lines = fs.readFileSync(path.join(ROOT, file), 'utf8').split(/\r?\n/);
  const seen = new Set();
  for (const row of git(['grep', '-n', '-o', '-I', '-F', '-w', ...pats, '--', file]).split('\n').filter(Boolean)) {
    const m = /^(?:.*?):(\d+):(.*)$/.exec(row);
    if (!m) continue;
    const line = Number(m[1]);
    const form = m[2];
    for (const name of owner.get(form) ?? []) {
      const key = `${line}|${name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const src = lines[line - 1] ?? '';
      const at = Math.max(0, src.indexOf(form) - 60);
      hits.push({ name, form, file, line, text: src.slice(at, at + 160).trim() });
    }
  }
}
hits.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line || a.name.localeCompare(b.name));
const byFile = {};
for (const h of hits) (byFile[h.file] ??= []).includes(h.name) || byFile[h.file].push(h.name);
const named = new Set(hits.map((h) => h.name));
const doc = {
  round: 1587,
  what: 'Committed files (outside this round\'s own data, harness and migration, and outside docs and markdown) naming a sarandi man of arsenalLedger.json, by stored spelling or its accent free form, whole word. Generated by scripts/qa/genArsenalOwed1587.mjs from a tree equal to HEAD. Each line is a lead for a re-bake after the apply, not a verdict: the reader checks the line is the man at Arsenal.',
  men: men.length,
  menNamed: named.size,
  menNotNamed: men.filter((n) => !named.has(n)),
  files: Object.keys(byFile).length,
  byFile,
  hits,
};
const text = JSON.stringify(doc, null, 1) + '\n';
console.log(`${men.length} sarandi men (${named.size} named somewhere), ${hits.length} lines in ${Object.keys(byFile).length} files`);
for (const [f, names] of Object.entries(byFile)) console.log(`  ${f}: ${names.length} (${names.slice(0, 5).join(', ')}${names.length > 5 ? ', ...' : ''})`);
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== text) { console.log('FAIL: owedToChat1587.json is not what the generator writes from HEAD'); process.exit(1); }
  console.log('ok: owedToChat1587.json equals the generator\'s output');
} else { fs.writeFileSync(OUT, text); console.log('wrote ' + OUT_REL); }
