/* Round 1565: write the migration that makes the live connections_puzzles table hold the shipped file's boards,
   and its checksummed, all or nothing form for production, from the lead's read only export of the table.

     node scripts/qa/genConnections1565.mjs <export.json>

   The export is (puzzle_id, sort_order, groups_json) for every row, read once with a SELECT. Every row whose board
   differs from src/data/connectionsPuzzles.ts is rewritten IN PLACE (same puzzle_id, same sort_order) and only while
   it still holds the exact board the export read. It writes:
     supabase/migrations/20261029120000_round_1565_connections_live.sql   (guard: jsonb equality with the exported board)
     scripts/qa/connections1565Applied.sql   (guard: md5(groups_json::text) of the exported board; the payload's own md5
                                              is checked first; anything but N of N raises and rolls back)
   It refuses unless the export and the file hold the same ids in the same order, and every board on both sides is a
   valid board (4 groups of 4, 16 different names), so the pool the game deals from keeps its size and order.
   It reads only the export and the repo; it never reaches the network. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { boardMd5 } from '../lib/pgJsonbText.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const [exportPath] = process.argv.slice(2);
if (!exportPath) { console.error('usage: node scripts/qa/genConnections1565.mjs <export.json>'); process.exit(2); }
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'gen1565-'));
fs.writeFileSync(path.join(TMP, 'e.mjs'), `export { connectionsPuzzles } from '${ROOT.replaceAll('\\', '/')}/src/data/connectionsPuzzles.ts';`);
await build({ entryPoints: [path.join(TMP, 'e.mjs')], bundle: true, format: 'esm', platform: 'node', outfile: path.join(TMP, 'b.mjs'), logLevel: 'error', alias: { '@': path.join(ROOT, 'src') } });
const { connectionsPuzzles: file } = await import(pathToFileURL(path.join(TMP, 'b.mjs')).href);

const groupsOf = raw => { const v = typeof raw === 'string' ? JSON.parse(raw) : raw; return Array.isArray(v) ? v : (v?.groups ?? []); };
const valid = gs => { const all = gs.flatMap(x => x.players ?? []); return gs.length === 4 && gs.every(x => (x.players ?? []).length === 4) && new Set(all).size === 16; };
const plain = gs => gs.map(g => ({ category: g.category, players: [...g.players], difficulty: g.difficulty }));
const rows = JSON.parse(fs.readFileSync(exportPath, 'utf8')).sort((a, b) => a.sort_order - b.sort_order);
const ids = rows.map(r => r.puzzle_id).join('|');
if (ids !== file.map(b => b.id).join('|')) throw new Error('the export and the file do not hold the same ids in the same order');
const fileById = new Map(file.map(b => [b.id, plain(b.groups)]));
const change = [];
for (const r of rows) {
  const old = groupsOf(r.groups_json);
  const now = fileById.get(r.puzzle_id);
  if (!valid(old) || !valid(now)) throw new Error(`${r.puzzle_id}: not a valid board on both sides`);
  if (boardMd5(old) !== boardMd5(now)) change.push({ id: r.puzzle_id, old, now });
}
const N = change.length;
const sqlText = v => `'${JSON.stringify(v).replace(/'/g, "''")}'`;

const migration = `-- Round 1565 (2026-10-29): Soccer Connections, every live board true, and one source for the file and the table.
--
-- UNAPPLIED. The lead applies it at a release's publish, on a day scripts/qa/connectionsDealtDay1553.mjs names as
-- clear for it (CONN_MIGRATION set to this file), away from 23:00 to 01:00 ET and never beside a gate on live tables.
-- Rehearsed in PGlite on the read only export of the live table (scripts/qa/rehearseConnections1565.mjs), never on
-- production. Generated by scripts/qa/genConnections1565.mjs from that export and src/data/connectionsPuzzles.ts.
--
-- Why: the game deals from this table and falls back to the shipped file, and the two had drifted apart. Round 1553
-- found 60 boards edited in the table and never in the file, and 76 boards only the table holds, and the cross check
-- (scripts/simConnectionsFacts.mjs over the export) found false members and boards with two right answers on 59 of
-- them. The file now holds every live board, the true one, in the table's order; this rewrites the ${N} rows whose live
-- board differs from it, IN PLACE: same puzzle_id, same sort_order, same row count. Every board before and after is a
-- valid board, so the pool the game deals from keeps its size and order and no daily reshuffles.
--
-- The guard: a row is rewritten only while it still holds the EXACT board the export read (jsonb equality). A row
-- that holds anything else is left alone and named in the NOTICE. A row already at the new board is counted, not
-- touched, so a re-run is a no-op. Expected NOTICE on the exported table: ${N} rewritten, 0 already current,
-- 0 drifted, 0 missing.

do $$
declare
  rewritten int := 0;
  already int := 0;
  drifted text[] := '{}';
  missing text[] := '{}';
  r record;
begin
  create temp table r1565_rows (puzzle_id text, old_groups jsonb, new_groups jsonb) on commit drop;
  insert into r1565_rows (puzzle_id, old_groups, new_groups) values
${change.map(c => `    ('${c.id}', ${sqlText(c.old)}, ${sqlText(c.now)})`).join(',\n')}
  ;

  for r in select puzzle_id, new_groups from r1565_rows loop
    if not exists (select 1 from public.connections_puzzles c where c.puzzle_id = r.puzzle_id) then
      missing := missing || r.puzzle_id;
    elsif exists (select 1 from public.connections_puzzles c where c.puzzle_id = r.puzzle_id and c.groups_json = r.new_groups) then
      already := already + 1;
    else
      update public.connections_puzzles c
         set groups_json = r.new_groups
       where c.puzzle_id = r.puzzle_id
         and c.groups_json = (select o.old_groups from r1565_rows o where o.puzzle_id = r.puzzle_id);
      if found then
        rewritten := rewritten + 1;
      else
        drifted := drifted || r.puzzle_id;
      end if;
    end if;
  end loop;
  drop table r1565_rows;
  raise notice 'Round 1565: % boards rewritten, % already current, % drifted from the exported board (left alone): %, % not in the table: %',
    rewritten, already, coalesce(array_length(drifted, 1), 0), drifted, coalesce(array_length(missing, 1), 0), missing;
end
$$;
`;

/* one line: a Windows checkout turns every line end into CRLF, and a payload with line ends would then fail its own
   checksum (it fails closed, but it would stop the apply) */
const payload = '[' + change.map(c => JSON.stringify({ id: c.id, h: boardMd5(c.old), n: c.now })).join(',') + ']';
if (payload.includes('$pl$')) throw new Error('the payload holds the quote tag');
const sum = crypto.createHash('md5').update(payload, 'utf8').digest('hex');
const applied = `-- Round 1565 for production: supabase/migrations/20261029120000_round_1565_connections_live.sql as one checksummed,
-- all or nothing step (the shape the lead used for Round 1553). Generated by scripts/qa/genConnections1565.mjs.
-- Guard: each of the ${N} rows is rewritten only while md5(groups_json::text) equals the hash of the board the read only
-- export held. The payload's own md5 is checked first, so a payload changed in transit applies nothing. Anything but
-- ${N} of ${N} (rewritten plus already current) raises and rolls back.
do $$
declare
  payload text := $pl$${payload}$pl$;
  rec record;
  rewritten int := 0;
  already int := 0;
  drifted text[] := '{}';
begin
  if md5(payload) <> '${sum}' then
    raise exception 'Round 1565: payload checksum mismatch, nothing applied';
  end if;
  for rec in select * from jsonb_to_recordset(payload::jsonb) as x(id text, h text, n jsonb) loop
    if exists (select 1 from public.connections_puzzles c where c.puzzle_id = rec.id and c.groups_json = rec.n) then
      already := already + 1;
    else
      update public.connections_puzzles c
         set groups_json = rec.n
       where c.puzzle_id = rec.id
         and md5(c.groups_json::text) = rec.h;
      if found then rewritten := rewritten + 1; else drifted := drifted || rec.id; end if;
    end if;
  end loop;
  if rewritten + already <> ${N} then
    raise exception 'Round 1565: % rewritten, % already current, drifted %: nothing applied', rewritten, already, drifted;
  end if;
  raise notice 'Round 1565: % rewritten, % already current, 0 drifted', rewritten, already;
end
$$;
`;
fs.writeFileSync(path.join(ROOT, 'supabase/migrations/20261029120000_round_1565_connections_live.sql'), migration);
fs.writeFileSync(path.join(ROOT, 'scripts/qa/connections1565Applied.sql'), applied);
console.log(`${N} rows to rewrite of ${rows.length}; payload md5 ${sum}; ids ${change.map(c => c.id).join(' ')}`);
