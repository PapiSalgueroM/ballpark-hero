// WHAT EACH NUMBER MEANS, because the same words mean different things:
//
// * Football titles come from CFB_TITLE_SEASONS: seasons the school was picked
//   national champion by the final AP poll or the final Coaches poll, 1936
//   through 2025 (the BCS and the Playoff carried the Coaches title). Shared
//   seasons count for both schools, which is why Colorado and Georgia Tech both
//   hold 1990. Two publishers agree on every season in it: the Wikipedia poll
//   era table and NCAA.com's year by year list of recognised champions.
//   The counts schools CLAIM are a different and much larger number and they do
//   not ship here: they depend on which selector you open, and the publishers
//   genuinely disagree (ESPN's recognised list gives Alabama 16 and Notre Dame
//   13, the schools claim 18 and 11).
// * Basketball titles come from NCAA_MBB_TITLE_SEASONS: NCAA Division I men's
//   tournament championships, from NCAA.com's championship history and the
//   Wikipedia by school table, which agree row for row.
// * Vacated titles are excluded and named, in CFB_VACATED_TITLES and
//   NCAA_MBB_VACATED_TITLES. That is why Louisville is a two title basketball
//   school here and USC a six title football one.
// * enrollment is the total fall headcount for ipedsUnitId in enrollmentYear,
//   from IPEDS. Six schools have no number at all: their second publisher was
//   counting a different set of campuses, so the figure did not ship and they
//   sit in COLLEGE_THIN.
// * There is no acceptance rate any more. It moved every admissions cycle, so
//   it rotted inside a saved page, and only 31 of the 70 schools had a second
//   publisher carrying one at all. The clue it used to fill now names the
//   conference tier instead, which is derived from data already here.
//
// The counts are DERIVED from the ledgers, never typed beside a school, so a
// school cannot drift away from the list it was counted off.

