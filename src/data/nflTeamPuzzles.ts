export function getDailyNflTeamPuzzle(): NflTeamPuzzle {
  const startDate = new Date('2024-01-01');
  const today = new Date();
  const daysDiff = Math.floor((today.getTime() - startDate.getTime()) / (1000 * 60 * 60 * 24));
  const puzzleIndex = daysDiff % nflTeamPuzzles.length;
  return nflTeamPuzzles[puzzleIndex];
}

export function getRandomNflTeamPuzzle(
  excludeRelocated: boolean = false,
  conference?: 'AFC' | 'NFC',
  division?: string
): NflTeamPuzzle {
  let filtered = nflTeamPuzzles;
  
  if (excludeRelocated) {
    filtered = filtered.filter(t => !t.isRelocated);
  }
  if (conference) {
    filtered = filtered.filter(t => t.conference === conference);
  }
  if (division) {
    filtered = filtered.filter(t => t.division === division);
  }
  
  return filtered[Math.floor(Math.random() * filtered.length)];
}

