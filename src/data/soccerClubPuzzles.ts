export const allClubNames: string[] = Array.from(
  new Set(
    soccerClubPuzzles.flatMap(p => [p.fullName, ...p.commonNames])
  )
).sort();

// Resolve alias to puzzle
export function resolvePuzzleByName(input: string): SoccerClubPuzzle | undefined {
  const lower = input.toLowerCase().trim();
  return soccerClubPuzzles.find(p =>
    p.fullName.toLowerCase() === lower ||
    p.commonNames.some(alias => alias.toLowerCase() === lower)
  );
}

// Daily puzzle — deterministic by date
export function getDailySoccerClubPuzzle(): SoccerClubPuzzle {
  const start = new Date('2024-01-01');
  const today = new Date();
  const diff = Math.floor((today.getTime() - start.getTime()) / (1000 * 60 * 60 * 24));
  return soccerClubPuzzles[diff % soccerClubPuzzles.length];
}

// Random puzzle, optionally filtered by league
export function getRandomSoccerClubPuzzle(leagueFilter?: string): SoccerClubPuzzle {
  let pool = soccerClubPuzzles;
  if (leagueFilter) pool = pool.filter(p => p.league === leagueFilter);
  if (!pool.length) pool = soccerClubPuzzles;
  return pool[Math.floor(Math.random() * pool.length)];
}
