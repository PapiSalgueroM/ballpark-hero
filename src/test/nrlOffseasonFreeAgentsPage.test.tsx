import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import type { ReactNode } from 'react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import { createNrlCareer, nrlOffseasonFreeAgentPreview, nrlRetentionPriority, readNrlCareerSave, reduceNrlCareer } from '@/lib/nrlCareer';
import { NRL_SAVE_KEY, nrlSavedLineupPreview, nrlStarterOptions } from '@/lib/nrlManager';
import { fenceKeyOf, saveFence } from '@/lib/saveFence';
import NrlTeamManager from '@/pages/NrlTeamManager';

vi.mock('@/components/game/GameNav', () => ({ GameNav: () => null }));
vi.mock('@/components/game/GameNavbar', () => ({ GameNavbar: () => null }));
vi.mock('@/components/game/RulesGate', () => ({ RulesGate: ({ children }: { children: ReactNode }) => <>{children}</> }));
vi.mock('@/components/seo/GameSeoContent', () => ({ default: () => null }));
vi.mock('@/components/seo/PageSeo', () => ({ default: () => null }));
vi.mock('@/hooks/useGameCompletion', () => ({ useGameCompletion: () => undefined }));

const fence = fenceKeyOf(NRL_SAVE_KEY);
const raw = () => localStorage.getItem(NRL_SAVE_KEY);
const click = (name: string) => fireEvent.click(screen.getByRole('button', { name }));
const review = () => { click('Club office'); click('Season review'); };
const show = () => render(<MemoryRouter initialEntries={['/nrl-team-manager']}><NrlTeamManager /></MemoryRouter>);
const currency = new Intl.NumberFormat('en-AU', { style: 'currency', currency: 'AUD', maximumFractionDigits: 0 });

afterEach(() => {
  cleanup();
  saveFence.release(NRL_SAVE_KEY);
  localStorage.clear();
});

it('reserves an expiring player before the ordinary offseason fill and keeps the choice through reload', () => {
  let career = createNrlCareer('storm', 4);
  while (career.season.phase !== 'complete') career = reduceNrlCareer(career, { type: 'advance' });
  const { year, clubId } = career.season;
  const priority = nrlRetentionPriority(career)!;
  const chosen = priority.options.find(option => option.quote.ok)!;
  const baseline = JSON.stringify(career);
  localStorage.setItem(NRL_SAVE_KEY, baseline);
  localStorage.setItem(fence, '4');
  const mounted = show();
  review();
  const option = () => screen.getByRole('combobox', { name: 'Player to retain' });
  expect(within(option()).getAllByRole('option')).toHaveLength(priority.options.length + 1);
  expect(raw()).toBe(baseline);
  fireEvent.change(option(), { target: { value: chosen.player.id } });
  const selected = reduceNrlCareer(career, { type: 'setRetentionPriority', year, clubId, playerId: chosen.player.id });
  expect(raw()).toBe(JSON.stringify(selected));
  expect(localStorage.getItem(fence)).toBe('5');
  expect(selected.players).toBe(career.players);
  mounted.unmount();
  show();
  review();
  expect(option()).toHaveValue(chosen.player.id);
  const normal = reduceNrlCareer(career, { type: 'startNextSeason' });
  const settled = reduceNrlCareer(selected, { type: 'startNextSeason' });
  expect(normal.season.squad.some(player => player.id === chosen.player.id)).toBe(false);
  expect(settled.season.squad.some(player => player.id === chosen.player.id)).toBe(true);
  click('Start 2027');
  expect(readNrlCareerSave(raw())).toEqual(settled);
  expect(localStorage.getItem(fence)).toBe('6');
  review();
  expect(screen.getByText(new RegExp('Retained ' + chosen.player.name))).toBeVisible();
});

it('saves the preference through Contracts and reload, then confirms the exact signings at rollover', () => {
  let career = createNrlCareer('storm', 4);
  while (career.season.phase !== 'complete') career = reduceNrlCareer(career, { type: 'advance' });
  const preview = nrlOffseasonFreeAgentPreview(career)!;
  const bytes = JSON.stringify(career);
  localStorage.setItem(NRL_SAVE_KEY, bytes);
  localStorage.setItem(fence, '4');
  const page = show();
  review();
  const openPreference = () => {
    const summary = screen.getByText('Fill open squad places', { exact: true });
    const details = summary.closest('details')!;
    fireEvent.click(summary);
    fireEvent(details, new Event('toggle'));
    return within(details);
  };
  const details = openPreference();
  const preference = 'Prefer free agents when starting 2027';
  const checkbox = details.getByRole('checkbox', { name: preference });
  expect(checkbox).not.toBeChecked();
  const planned = details.getByRole('list', { name: 'Projected free-agent signings' });
  expect(within(planned).getAllByRole('listitem').map(row => row.getAttribute('data-nrl-fill-player'))).toEqual(preview.signings.map(row => row.playerId));
  expect(details.getByText(new RegExp(currency.format(preview.available).replace('$', '\\$') + ' cap room'))).toBeVisible();
  expect(raw()).toBe(bytes);
  expect(localStorage.getItem(fence)).toBe('4');
  fireEvent.click(checkbox);
  expect(checkbox).toBeChecked();
  expect(readNrlCareerSave(raw())).toEqual({ ...career, preferFreeAgents: true });
  expect(localStorage.getItem(fence)).toBe('5');
  click('Contracts');
  click('Season review');
  expect(openPreference().getByRole('checkbox', { name: preference })).toBeChecked();
  page.unmount();
  const restored = show();
  review();
  expect(openPreference().getByRole('checkbox', { name: preference })).toBeChecked();
  expect(localStorage.getItem(fence)).toBe('5');
  click('Start 2027');
  const expected = reduceNrlCareer(career, { type: 'startNextSeason', freeAgents: { fromYear: 2026, clubId: 'storm' } });
  expect(readNrlCareerSave(raw())).toEqual(expected);
  expect(localStorage.getItem(fence)).toBe('6');
  restored.unmount();
  show();
  review();
  fireEvent.click(screen.getByText('Free agents signed for 2027 · ' + preview.signings.length, { exact: true }));
  const receipt = screen.getByRole('list', { name: 'Recorded free-agent signings' });
  expect(within(receipt).getAllByRole('listitem').map(row => row.textContent)).toEqual(preview.signings.map(row =>
    row.playerName + ' · ' + row.role + ' · ' + currency.format(row.annualSalary)));
  expect(raw()).toBe(JSON.stringify(expected));
  expect(localStorage.getItem(fence)).toBe('6');
});

it('refuses to save the preference over a newer career from another tab', () => {
  let career = createNrlCareer('storm', 4);
  while (career.season.phase !== 'complete') career = reduceNrlCareer(career, { type: 'advance' });
  localStorage.setItem(NRL_SAVE_KEY, JSON.stringify(career));
  localStorage.setItem(fence, '4');
  show();
  review();
  const summary = screen.getByText('Fill open squad places', { exact: true });
  const details = summary.closest('details')!;
  fireEvent.click(summary);
  fireEvent(details, new Event('toggle'));
  const checkbox = within(details).getByRole('checkbox', { name: 'Prefer free agents when starting 2027' });

  const newer = JSON.stringify(reduceNrlCareer(career, { type: 'setLeagueRecruitment', year: 2026, clubId: 'storm', enabled: true }));
  localStorage.setItem(NRL_SAVE_KEY, newer);
  localStorage.setItem(fence, '5');
  fireEvent.click(checkbox);
  expect(checkbox).not.toBeChecked();
  expect(raw()).toBe(newer);
  expect(localStorage.getItem(fence)).toBe('5');
});

it('previews lineup carryover without writing, then restores separate presets next season', () => {
  const year = 2026, clubId = 'storm';
  let career = createNrlCareer(clubId, 4, year);
  const run = (action: Parameters<typeof reduceNrlCareer>[1]) => { career = reduceNrlCareer(career, action); };
  const reserve = nrlStarterOptions(career.season, 'Fullback').find(player => player.id !== career.season.lineup.Fullback)!;
  run({ type: 'saveLineup', year, clubId });
  run({ type: 'selectStarter', role: 'Fullback', playerId: reserve.id });
  run({ type: 'saveLineup', year, clubId, slot: 'rotation' });
  run({ type: 'applySavedLineup', previewKey: nrlSavedLineupPreview(career.season, career.savedLineup!)!.key });
  while (career.season.phase !== 'complete') run({ type: 'advance' });
  const bytes = JSON.stringify(career);
  localStorage.setItem(NRL_SAVE_KEY, bytes);
  localStorage.setItem(fence, '4');
  const page = show();
  review();
  const option = screen.getByRole('checkbox', { name: 'Keep saved lineups for 2027' });
  expect(option).not.toBeChecked();
  fireEvent.click(option);
  const summary = screen.getByRole('list', { name: 'Saved lineup changes for 2027' });
  const [first, rotation] = within(summary).getAllByRole('listitem');
  expect(first).toHaveTextContent('First choice: 5 starter changes, 3 bench changes, new goal kicker');
  expect(rotation).toHaveTextContent('Rotation: 4 starter changes, 2 bench changes, new goal kicker');
  expect(raw()).toBe(bytes);
  expect(localStorage.getItem(fence)).toBe('4');
  click('Start 2027');
  const next = reduceNrlCareer(career, { type: 'startNextSeason', carryLineups: { fromYear: year, clubId } });
  expect(raw()).toBe(JSON.stringify(next));
  expect(localStorage.getItem(fence)).toBe('5');
  page.unmount();
  show();
  click('Squad');
  fireEvent.click(screen.getByText('Saved lineup', { exact: true }));
  click('Rotation');
  click('Apply saved lineup');
  expect(readNrlCareerSave(raw())?.season.lineup.Fullback).toBe(reserve.id);
  expect(localStorage.getItem(fence)).toBe('6');
});
