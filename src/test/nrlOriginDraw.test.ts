import { describe, expect, it } from 'vitest';
import { nrlSeasonPlan } from '@/data/nrlManagerSeasons';
import { createNrlCareer, createNrlCustomCareer, nrlCaretakerOpenings, readNrlCareerSave, reduceNrlCareer, type NrlCareerState } from '@/lib/nrlCareer';
import { nrlLeagueFixtures } from '@/lib/nrlLeagueBook';
import { nrlClubOriginAbsences, nrlNextRound, nrlRoundFixtures } from '@/lib/nrlManager';
import { sameNrlCareer } from '@/lib/nrlSaveSlots';

const year = 2026;
const drawModel = 'origin-breaks-2026' as const;
const advance = (career: NrlCareerState) => reduceNrlCareer(career, { type: 'advance' });
const reload = (career: NrlCareerState) => readNrlCareerSave(JSON.stringify(career));

function finish(career: NrlCareerState) {
  for (let index = 0; index < 32 && career.season.phase !== 'complete'; index++) career = advance(career);
  expect(career.season.phase).toBe('complete');
  return career;
}

describe('generated 2026 draw with Origin breaks', () => {
  it('preserves every opponent and home assignment with a shorter round before each Origin game', () => {
    const original = nrlSeasonPlan(year);
    const { clubs, draw } = nrlSeasonPlan(year, drawModel);
    expect(draw).toHaveLength(27);
    expect([12, 15, 18].map(round => draw[round - 1].length)).toEqual([5, 5, 5]);
    expect([11, 13, 14, 16, 17, 19].map(round => draw[round - 1].length)).toEqual([8, 8, 8, 8, 8, 8]);
    expect(draw.flat().map(pair => pair.join('/')).sort()).toEqual(original.draw.flat().map(pair => pair.join('/')).sort());

    let previousRound = new Set<string>();
    let previousPairs = new Set<string>();
    for (const fixtures of draw) {
      const active = new Set<string>(fixtures.flat());
      const pairs = fixtures.map(pair => [...pair].sort().join('/'));
      expect(active.size).toBe(fixtures.length * 2);
      if (previousRound.size) expect(clubs.filter(({ id }) => !active.has(id) && !previousRound.has(id))).toEqual([]);
      expect(pairs.some(pair => previousPairs.has(pair))).toBe(false);
      previousRound = active;
      previousPairs = new Set(pairs);
    }
  });

  it('settles and reloads the same generated draw live and in its archive, including the custom slot', () => {
    const short = createNrlCareer('rabbitohs', 3, year, false, false, drawModel);
    const old = createNrlCareer('rabbitohs', 3, year);
    const custom = createNrlCustomCareer('rabbitohs', 3, year, {
      name: 'Harbour Eels RFC', ground: 'Harbour Field', colour: 'teal',
    }, false, false, drawModel)!;
    expect(nrlRoundFixtures(short.season)).toHaveLength(8);
    expect(nrlRoundFixtures(old.season)).toHaveLength(7);
    expect(nrlNextRound(short.season)).toMatchObject({ clubMatch: { homeId: 'rabbitohs', awayId: 'panthers' } });
    expect(nrlNextRound(custom.season)).toEqual(nrlNextRound(short.season));
    expect(reload(custom)).toEqual(custom);
    expect(sameNrlCareer(short, old)).toBe(false);

    const priced = reduceNrlCareer(short, { type: 'setTicketTier', year, round: 1, tier: 'value' });
    const withAttendance = reduceNrlCareer(priced, { type: 'setSupporterAttendance', year, clubId: 'rabbitohs', enabled: true });
    const played = advance(withAttendance);
    const oldPlayed = advance(old);
    expect(reload(played)).toEqual(played);
    expect(reload(oldPlayed)).toEqual(oldPlayed);
    expect(reload({ ...played, season: { ...played.season, drawModel: undefined } })).toBeNull();
    expect(reload({ ...oldPlayed, season: { ...oldPlayed.season, drawModel } })).toBeNull();

    const next = reduceNrlCareer(finish(played), { type: 'startNextSeason' });
    expect(next.season.year).toBe(2027);
    expect(next.history[0].attendanceForm).toMatch(/^[WDL]{24}$/);
    expect(nrlLeagueFixtures(next.latestLeagueBook).filter(match => match.round === 12)).toHaveLength(5);
    expect(reload(next)).toEqual(next);
    expect(reload({ ...next, season: { ...next.season, drawModel: undefined } })).toBeNull();
  });

  it('uses the generated bye for Origin and keeps it through a live caretaker save', () => {
    let career: NrlCareerState = {
      ...createNrlCareer('storm', 3, year, true, false, drawModel),
      originClubCalendar: true, originClubRecovery: true,
    };
    career = reduceNrlCareer(career, { type: 'signSponsor', year, clubId: 'storm', offer: 'twoSeason' });
    while (career.season.round < 12) career = advance(career);
    expect(nrlNextRound(career.season).clubStatus).toBe('bye');
    expect(career.season.originStandDown?.[0].clubs.storm).toContain('storm-1-0');
    expect(nrlClubOriginAbsences(career.season)).toEqual([]);
    career = advance(advance(career));
    expect(nrlCaretakerOpenings(career).map(job => job.clubId)).toContain('dragons');
    const moved = reduceNrlCareer(career, {
      type: 'acceptCaretakerJob', year, round: 14, clubId: 'storm', destinationId: 'dragons',
    });
    expect(moved.season.caretaker?.drawModel).toBe(drawModel);
    expect(reload(moved)).toEqual(moved);
    expect(reload({ ...moved, season: { ...moved.season, caretaker: { ...moved.season.caretaker!, drawModel: undefined } } })).toBeNull();

    const live = reduceNrlCareer(moved, { type: 'startLive' });
    expect(live.season.live).toBeDefined();
    expect(reload(live)).toEqual(live);
    const settled = reduceNrlCareer(live, { type: 'finishLive', year, round: 14, tactic: live.season.tactic });
    expect(settled.season.results).toEqual(advance(moved).season.results);
    const next = reduceNrlCareer(finish(settled), { type: 'startNextSeason' });
    expect(next.season.year).toBe(2027);
    expect(reload(next)).toEqual(next);
  });
});
