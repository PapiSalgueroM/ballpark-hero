/* QA (qa-sc): the phone's money apps on a seeded save. Buys a house the player cannot fully afford,
   reads every number before and after, and screenshots each screen. Env: INJECT, W, H, NW (net worth to seed). */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const pw = (await import(pathToFileURL(path.resolve('scripts/lib/playwrightLoader.mjs')).href)).default;
const BASE = process.env.BASE || 'http://localhost:4173';
const OUT = process.env.RC_OUT || '.tmp-fx/out';
fs.mkdirSync(OUT, { recursive: true });
const W = Number(process.env.W || 390), H = Number(process.env.H || 844);
const TAG = process.env.TAG || 'shop';
const seed = JSON.parse(fs.readFileSync(process.env.INJECT, 'utf8'));
seed.netWorth = Number(process.env.NW || 2);
seed.purchasedItems = []; seed.properties = [];
const browser = await pw.chromium.launch({ args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, hasTouch: W < 768, isMobile: W < 768 });
await ctx.addInitScript(v => { try { localStorage.setItem('cookie-consent', 'essential'); if (!sessionStorage.getItem('qa')) { localStorage.setItem('soccerCareerSave', v); sessionStorage.setItem('qa', '1'); } } catch {} }, JSON.stringify(seed));
const page = await ctx.newPage();
await page.route(/supabase\.co/, r => r.abort());
const errs = [];
page.on('pageerror', e => errs.push(String(e).slice(0, 300)));
await page.goto(BASE + '/soccer-career', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2500);
const log = { steps: [] };
let n = 0;
const shot = async name => { n++; const f = `${TAG}-${String(n).padStart(2, '0')}-${name}.jpg`; await page.screenshot({ path: path.join(OUT, f), type: 'jpeg', quality: 55 }); return f; };
const sv = () => page.evaluate(() => { const s = JSON.parse(localStorage.getItem('soccerCareerSave')); return { nw: s.netWorth, items: s.purchasedItems, props: s.properties, yearly: s.customYearlyCosts, money: s.money ? { vault: s.money.vault } : null }; });
const hubNw = () => page.evaluate(() => { const t = [...document.querySelectorAll('div')].find(d => d.innerText.trim() === 'Net Worth'); return t ? t.previousElementSibling?.innerText : null; });
const dlg = () => page.evaluate(() => { const d = [...document.querySelectorAll('[aria-modal="true"],[role="dialog"]')].pop(); return d ? d.innerText.replace(/\s+/g, ' ').slice(0, 700) : null; });
const clickText = (re) => page.evaluate(src => { const r = new RegExp(src); const d = [...document.querySelectorAll('[aria-modal="true"],[role="dialog"]')].pop() || document; const b = [...d.querySelectorAll('button')].find(b => r.test(b.innerText.trim()) && !b.disabled); if (b) { b.click(); return b.innerText.trim().slice(0, 60); } return null; }, re.source);
log.start = { save: await sv(), hub: await hubNw() };
await page.click('[data-career-utility="phone"]'); await page.waitForTimeout(800);
await page.click('[data-phone-app="shop"]'); await page.waitForTimeout(700);
log.shopHome = await dlg(); log.shots = [await shot('shop-home')];
log.cat = await clickText(/Where you live/); await page.waitForTimeout(700);
log.catText = await dlg(); log.shots.push(await shot('shop-property'));
log.before = await sv();
log.buy = await page.evaluate(() => { const d = [...document.querySelectorAll('[aria-modal="true"],[role="dialog"]')].pop(); const cards = [...d.querySelectorAll('div.rounded-xl')]; const card = cards.find(c => /Luxury House/.test(c.innerText)); if (!card) return 'no card'; const b = card.querySelector('button'); if (!b) return 'no button: ' + card.innerText.replace(/\s+/g, ' ').slice(0, 200); const out = { text: card.innerText.replace(/\s+/g, ' ').slice(0, 200), disabled: b.disabled, label: b.innerText }; if (!b.disabled) b.click(); return out; });
await page.waitForTimeout(900);
log.after = await sv();
log.afterText = await dlg(); log.shots.push(await shot('shop-after-buy'));
await page.keyboard.press('Escape'); await page.waitForTimeout(600);
log.hubAfter = await hubNw(); log.shots.push(await shot('hub-after-buy'));
log.errs = errs;
fs.writeFileSync(path.join(OUT, `${TAG}.json`), JSON.stringify(log, null, 1));
console.log(JSON.stringify({ start: log.start, cat: log.cat, before: log.before, buy: log.buy, after: log.after, hubAfter: log.hubAfter, errs }, null, 1).slice(0, 3000));
await browser.close();
console.log('SHOPWALK DONE');
