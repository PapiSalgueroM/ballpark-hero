/* QA (qa-sc): two tabs on one Soccer Career save. Tab A plays a season; tab B, still open on the
   old screen, presses Next Season. Does A's season survive? Env: INJECT (a playing-phase save), W, H. */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const pw = (await import(pathToFileURL(path.resolve('scripts/lib/playwrightLoader.mjs')).href)).default;
const BASE = process.env.BASE || 'http://localhost:4173';
const OUT = process.env.RC_OUT || '.tmp-fx/out';
fs.mkdirSync(OUT, { recursive: true });
const W = Number(process.env.W || 390), H = Number(process.env.H || 844);
const inj = fs.readFileSync(process.env.INJECT, 'utf8');
const browser = await pw.chromium.launch({ args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, hasTouch: W < 768, isMobile: W < 768 });
await ctx.addInitScript(() => { try { localStorage.setItem('cookie-consent', 'essential'); } catch {} });
const log = { steps: [] };
const A = await ctx.newPage();
await A.route(/supabase\.co/, r => r.abort());
await A.goto(BASE + '/soccer-career', { waitUntil: 'domcontentloaded' });
await A.evaluate(v => localStorage.setItem('soccerCareerSave', v), inj);
await A.reload({ waitUntil: 'domcontentloaded' }); await A.waitForTimeout(2500);
const B = await ctx.newPage();
await B.route(/supabase\.co/, r => r.abort());
await B.goto(BASE + '/soccer-career', { waitUntil: 'domcontentloaded' }); await B.waitForTimeout(2500);
const read = p => p.evaluate(() => { const s = JSON.parse(localStorage.getItem('soccerCareerSave')); return { phase: s.phase, age: s.age, seasons: s.seasons.length, last: s.seasons.at(-1) && { year: s.seasons.at(-1).year, club: s.seasons.at(-1).club, apps: s.seasons.at(-1).apps, goals: s.seasons.at(-1).goals, rating: s.seasons.at(-1).rating }, nw: s.netWorth }; });
const uiAge = p => p.evaluate(() => (document.querySelector('[data-career-action-bar]')?.innerText || '').replace(/\s+/g, ' ').slice(-20));
log.start = await read(A);
log.uiA0 = await uiAge(A); log.uiB0 = await uiAge(B);
const next = async p => p.evaluate(() => { const b = [...document.querySelectorAll('[data-career-action-bar] button')].find(x => /^Next Season/.test(x.innerText.trim())); if (b) { b.click(); return true; } return false; });
log.aPressed = await next(A); await A.waitForTimeout(1500);
log.afterA = await read(A);
await A.screenshot({ path: path.join(OUT, 'twotab-A-after-season.jpg'), type: 'jpeg', quality: 55 });
log.uiB1 = await uiAge(B);
log.bPressed = await next(B); await B.waitForTimeout(1500);
log.afterB = await read(B);
await B.screenshot({ path: path.join(OUT, 'twotab-B-after-press.jpg'), type: 'jpeg', quality: 55 });
await A.reload({ waitUntil: 'domcontentloaded' }); await A.waitForTimeout(2500);
log.aAfterReload = await read(A);
await A.screenshot({ path: path.join(OUT, 'twotab-A-reloaded.jpg'), type: 'jpeg', quality: 55 });
log.verdict = JSON.stringify(log.afterA.last) === JSON.stringify(log.aAfterReload.last) ? 'A season kept' : 'A season REPLACED by B';
fs.writeFileSync(path.join(OUT, 'twotab.json'), JSON.stringify(log, null, 1));
console.log(JSON.stringify(log, null, 1).slice(0, 2500));
await browser.close();
console.log('TWOTAB DONE');
